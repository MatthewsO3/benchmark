"""Token-usage and cost accounting for LLM calls."""
from dataclasses import dataclass


@dataclass
class TokenUsage:
    """Token counts and billed cost for one or more LLM calls.

    Captures every token category the OpenAI/OpenRouter usage payloads expose,
    so the benchmark can report a complete picture rather than just in/out/total:

    :param input_tokens: Prompt tokens sent to the model (billed input).
    :param output_tokens: Completion tokens generated by the model.
    :param total_tokens: Combined prompt + completion tokens.
    :param cached_tokens: Prompt tokens served from the provider's read cache
        (a subset of ``input_tokens``; cheaper than uncached input).
    :param cache_write_tokens: Prompt tokens written INTO the cache this call
        (some providers bill these at a premium; 0 when not reported).
    :param reasoning_tokens: Hidden chain-of-thought / reasoning tokens counted
        within the completion (a subset of ``output_tokens`` on reasoning
        models; 0 when not reported).
    :param uncached_input_tokens: Prompt tokens NOT served from cache
        (``input_tokens - cached_tokens``; the portion billed at full input
        rate). Derived, kept explicit so per-call cost drivers are visible.
    :param cost_usd: Billed cost in US dollars.
    """

    input_tokens: int = 0
    output_tokens: int = 0
    total_tokens: int = 0
    cached_tokens: int = 0
    cache_write_tokens: int = 0
    reasoning_tokens: int = 0
    uncached_input_tokens: int = 0
    cost_usd: float = 0.0

    def __add__(self, other: "TokenUsage") -> "TokenUsage":
        """Add two usage records field by field.

        :param other: The usage record to add to this one.
        :return: A new :class:`TokenUsage` holding the summed fields.
        """
        return TokenUsage(
            input_tokens=self.input_tokens + other.input_tokens,
            output_tokens=self.output_tokens + other.output_tokens,
            total_tokens=self.total_tokens + other.total_tokens,
            cached_tokens=self.cached_tokens + other.cached_tokens,
            cache_write_tokens=self.cache_write_tokens + other.cache_write_tokens,
            reasoning_tokens=self.reasoning_tokens + other.reasoning_tokens,
            uncached_input_tokens=self.uncached_input_tokens + other.uncached_input_tokens,
            cost_usd=self.cost_usd + other.cost_usd,
        )

    def as_dict(self) -> dict:
        """Return a plain dict of every token field (for JSONL records).

        :return: Mapping of each usage field name to its value.
        """
        return {
            "input": self.input_tokens,
            "output": self.output_tokens,
            "total": self.total_tokens,
            "cached": self.cached_tokens,
            "cache_write": self.cache_write_tokens,
            "reasoning": self.reasoning_tokens,
            "uncached_input": self.uncached_input_tokens,
            "cost_usd": self.cost_usd,
        }

    @classmethod
    def from_openai_usage(cls, usage) -> "TokenUsage":
        """Build a record from a raw OpenAI/OpenRouter ``usage`` object.

        Used for the agent call, which goes through the raw OpenAI SDK. Reads
        the nested ``prompt_tokens_details`` (cached / cache-write input) and
        ``completion_tokens_details`` (reasoning tokens) blocks when present.

        :param usage: The ``usage`` object (or dict) from a chat-completion
            response; may be ``None``.
        :return: A populated :class:`TokenUsage`.
        """
        if usage is None:
            return cls()
        data = usage.model_dump() if hasattr(usage, "model_dump") else dict(usage)
        prompt_details = data.get("prompt_tokens_details") or {}
        completion_details = data.get("completion_tokens_details") or {}
        input_tokens = data.get("prompt_tokens", 0) or 0
        cached = prompt_details.get("cached_tokens", 0) or 0
        return cls(
            input_tokens=input_tokens,
            output_tokens=data.get("completion_tokens", 0) or 0,
            total_tokens=data.get("total_tokens", 0) or 0,
            cached_tokens=cached,
            # OpenRouter/Anthropic expose cache-write under a few names.
            cache_write_tokens=(
                prompt_details.get("cache_write_tokens")
                or prompt_details.get("cache_creation_tokens")
                or data.get("cache_creation_input_tokens")
                or 0
            ),
            reasoning_tokens=completion_details.get("reasoning_tokens", 0) or 0,
            uncached_input_tokens=max(input_tokens - cached, 0),
            cost_usd=data.get("cost", 0.0) or 0.0,
        )

    @classmethod
    def from_langchain_message(cls, message) -> "TokenUsage":
        """Build a record from a langchain ``AIMessage``.

        Used for the answerer call. Token counts come from ``usage_metadata``;
        cached/cache-write/reasoning tokens and cost come from the provider
        block in ``response_metadata['token_usage']``.

        :param message: The langchain response message.
        :return: A populated :class:`TokenUsage`.
        """
        meta = getattr(message, "usage_metadata", None) or {}
        provider = (getattr(message, "response_metadata", None) or {}).get("token_usage", {}) or {}
        prompt_details = provider.get("prompt_tokens_details") or {}
        completion_details = provider.get("completion_tokens_details") or {}
        # langchain also surfaces structured details on usage_metadata itself.
        input_details = meta.get("input_token_details") or {}
        output_details = meta.get("output_token_details") or {}
        input_tokens = meta.get("input_tokens", 0) or 0
        cached = (prompt_details.get("cached_tokens")
                  or input_details.get("cache_read")
                  or 0)
        return cls(
            input_tokens=input_tokens,
            output_tokens=meta.get("output_tokens", 0) or 0,
            total_tokens=meta.get("total_tokens", 0) or 0,
            cached_tokens=cached,
            cache_write_tokens=(
                prompt_details.get("cache_write_tokens")
                or input_details.get("cache_creation")
                or 0
            ),
            reasoning_tokens=(
                completion_details.get("reasoning_tokens")
                or output_details.get("reasoning")
                or 0
            ),
            uncached_input_tokens=max(input_tokens - cached, 0),
            cost_usd=provider.get("cost", 0.0) or 0.0,
        )
